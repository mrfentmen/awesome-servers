import { test } from 'node:test';
import assert from 'node:assert/strict';
import { htmlTable, buildStyledReportHtml, validateHtml } from '../dist/util.js';

test('htmlTable escapes cells and renders header + body rows', () => {
  const html = htmlTable('Invoices <2026>', ['Item', 'Amount'], [['A & B', '<b>5</b>']]);
  assert.ok(html.includes('<h1>Invoices &lt;2026&gt;</h1>'));
  assert.ok(html.includes('<th>Item</th>'));
  assert.ok(html.includes('<td>A &amp; B</td>'));
  assert.ok(html.includes('<td>&lt;b&gt;5&lt;/b&gt;</td>'));

  const headerless = htmlTable(undefined, undefined, [['x']]);
  assert.ok(!headerless.includes('<th>'));
  assert.ok(headerless.includes('<td>x</td>'));
});

test('buildStyledReportHtml embeds the stylesheet, title and meta line', () => {
  const html = buildStyledReportHtml('Q3 Report', 'generated by docraptor-mcp', ['K', 'V'], [['a', 1]]);
  assert.ok(html.includes('<style>'));
  assert.ok(html.includes('<h1>Q3 Report</h1>'));
  assert.ok(html.includes('<p class="meta">generated by docraptor-mcp</p>'));
  assert.ok(html.includes('<th>K</th>'));
  assert.ok(html.includes('<td>a</td>'));
  assert.ok(html.endsWith('</body></html>'));

  const bare = buildStyledReportHtml('T', ' ', undefined, []);
  assert.ok(!bare.includes('class="meta"'));
  assert.ok(!bare.includes('<th>'));
});

test('validateHtml flags structural problems without calling the API', () => {
  const good = validateHtml('<html><head></head><body><div><p>ok</p></div></body></html>');
  assert.deepEqual(good, { ok: true, issues: [] });

  const noHead = validateHtml('<html><body>hi</body></html>');
  assert.ok(noHead.issues.some((i) => i.includes('missing <head>')));
  assert.equal(noHead.ok, false);

  const unbalanced = validateHtml('<html><head></head><body><div><p>hi</div></body></html>');
  assert.ok(unbalanced.issues.some((i) => i.includes('tag balance')));

  const insecure = validateHtml('<html><head></head><body><img src="http://x/y.png"></body></html>');
  assert.ok(insecure.issues.some((i) => i.includes('insecure http://')));

  assert.deepEqual(validateHtml('   ').issues, ['document_content is empty']);
});